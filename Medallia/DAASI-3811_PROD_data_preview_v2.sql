-- 2d. What your role can see of the prospect source, which is where the prospect procedure gets its rows.
--     Line 3 above 0: the prospect statements in Part 3 will have rows to work on.
--     Line 1 is 0:    your role is shown no prospect transactions at all. The prospect file can then only be
--                     tested with data by the role the tasks use.
--     Line 1 above 0 with NEWEST_DAY well before today, or only today: the source keeps a short window.
SELECT '1 Prospect transactions your role can see' AS WHAT,
       COUNT(*) AS ROW_COUNT,
       MIN(F.TRANSACTION_DT)::DATE AS OLDEST_DAY,
       MAX(F.TRANSACTION_DT)::DATE AS NEWEST_DAY
FROM DAAS_PROD.HPDB.PROSPECT_TRANSACTION_FACT F
UNION ALL
SELECT '2 Of those, with a prospect customer row',
       COUNT(*),
       MIN(F.TRANSACTION_DT)::DATE,
       MAX(F.TRANSACTION_DT)::DATE
FROM DAAS_PROD.HPDB.PROSPECT_TRANSACTION_FACT F
JOIN DAAS_PROD.HPDB_VW.PROSPECT_CUST_DIM_FINAL_VW C
    ON C.PROSPECT_ID = F.PROSPECT_ID
UNION ALL
SELECT '3 Of those, on the prospect test day',
       COUNT(*),
       MIN(F.TRANSACTION_DT)::DATE,
       MAX(F.TRANSACTION_DT)::DATE
FROM DAAS_PROD.HPDB.PROSPECT_TRANSACTION_FACT F
JOIN DAAS_PROD.HPDB_VW.PROSPECT_CUST_DIM_FINAL_VW C
    ON C.PROSPECT_ID = F.PROSPECT_ID
WHERE F.TRANSACTION_DT = $PRO_DATE
ORDER BY 1;

