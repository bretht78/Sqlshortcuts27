-- 2a. Where the tag has something to show. These are the rows the real tasks sent since 10/21 (read from the
--     two archives) that belong to a reservation coded LUX in LMS today: one line per file and day.
--     RUN_DAY is the day the file covers: the check-out day for the invitation file, the transaction day for the
--     prospect file. No line for a file = no stay coded LUX has gone out in that file since 10/21.
WITH LUX AS (
    SELECT PROPERTY_CD, RESERVATION_ID
    FROM DAAS_PROD.DAAS_CORE_HOTEL.LMS73_HOTEL_RESERVATIONS_FACT
    WHERE DELETE_IND = 'N'
    AND TRIM(LOYALTY) IN ('LUX')
    GROUP BY PROPERTY_CD, RESERVATION_ID
),
SENT AS (
    SELECT 'Invitation file' AS FILE_NAME, TRY_TO_DATE(TRANSACTION_DATE) AS RUN_DAY, UNIT_ID, RESERVATION_NUMBER
    FROM DAAS_PROD.DAAS_CORE.MEDALLIA_V_CUSTOMER_INVITATION_ARCHIVE
    WHERE SNOWFLAKE_CREATED_DT >= '2026-10-21'
    UNION ALL
    SELECT 'Prospect file', TRY_TO_DATE(TRANSACTION_DATE), UNIT_ID, RESERVATION_NUMBER
    FROM DAAS_PROD.HPDB.MEDALLIA_PROSPECT_INVITATION_FILE_ARCHIVE
    WHERE CREATED_DTTM >= '2026-10-21'
)
SELECT S.FILE_NAME,
       S.RUN_DAY,
       COUNT(*) AS ROWS_SENT_ON_A_LUX_RESERVATION
FROM SENT S
JOIN LUX
    ON LUX.PROPERTY_CD = S.UNIT_ID
    AND LUX.RESERVATION_ID = TRY_TO_NUMBER(S.RESERVATION_NUMBER)
GROUP BY S.FILE_NAME, S.RUN_DAY
ORDER BY S.FILE_NAME, S.RUN_DAY DESC;

-- 2b. The invitation test day: the newest RUN_DAY that 2a lists for the invitation file. If 2a lists none, it is
--     the day PROD's file table holds now.
SET INV_DATE = (
    SELECT COALESCE(
        (SELECT MAX(TRY_TO_DATE(A.TRANSACTION_DATE))
         FROM DAAS_PROD.DAAS_CORE.MEDALLIA_V_CUSTOMER_INVITATION_ARCHIVE A
         JOIN DAAS_PROD.DAAS_CORE_HOTEL.LMS73_HOTEL_RESERVATIONS_FACT L
             ON L.PROPERTY_CD = A.UNIT_ID
             AND L.RESERVATION_ID = TRY_TO_NUMBER(A.RESERVATION_NUMBER)
         WHERE A.SNOWFLAKE_CREATED_DT >= '2026-10-21'
         AND L.DELETE_IND = 'N'
         AND TRIM(L.LOYALTY) IN ('LUX')),
        (SELECT MAX(TRY_TO_DATE(TRANSACTION_DATE)) FROM DAAS_PROD.DAAS_CORE.MEDALLIA_V_CUSTOMER_INVITATION_COMPLETE)));

-- 2c. The prospect test day: the newest finished day the prospect source still holds for your role. Failing
--     that, today. Failing that, the day PROD's file table holds now.
SET PRO_DATE = (
    SELECT COALESCE(
        (SELECT MAX(F.TRANSACTION_DT)::DATE
         FROM DAAS_PROD.HPDB.PROSPECT_TRANSACTION_FACT F
         JOIN DAAS_PROD.HPDB_VW.PROSPECT_CUST_DIM_FINAL_VW C
             ON C.PROSPECT_ID = F.PROSPECT_ID
         WHERE F.TRANSACTION_DT < CURRENT_DATE()),
        (SELECT MAX(F.TRANSACTION_DT)::DATE
         FROM DAAS_PROD.HPDB.PROSPECT_TRANSACTION_FACT F
         JOIN DAAS_PROD.HPDB_VW.PROSPECT_CUST_DIM_FINAL_VW C
             ON C.PROSPECT_ID = F.PROSPECT_ID
         WHERE F.TRANSACTION_DT <= CURRENT_DATE()),
        (SELECT MAX(TRY_TO_DATE(TRANSACTION_DATE)) FROM DAAS_PROD.HPDB.MEDALLIA_PROSPECT_INVITATION_FILE)));

