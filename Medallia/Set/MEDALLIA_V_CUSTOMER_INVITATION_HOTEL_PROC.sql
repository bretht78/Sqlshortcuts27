CREATE OR REPLACE PROCEDURE DAAS_COMMON.MEDALLIA_V_CUSTOMER_INVITATION_HOTEL_PROC("RUNDATE" DATE)
RETURNS VARCHAR(16777216)
LANGUAGE SQL
EXECUTE AS CALLER
AS 'BEGIN

--Author: Andrew King
--Date Created: 2023-06-22
--Description: Replicates the EDW_MAIN.MEDALLIA_V_CUSTOMER_INVITATION view in Teradata to generate hotel visits and assosicated trip details for a specific date.
--Updates:
--2024-01-10 - added GUEST_ID and PROP_ID for host joins
--2024-01-18 - changed the HOST_CODE logic to use HOST_ID instead of HOST_NAME
--2024-01-25 - changed host join qualifier from dominant_prop_cd to prop_cd of hotel_rev visit
--2024-08-22 - fixing TIER_CD bug that is giving subtier precedence over tier
--2024-09-05 - adding new subtier logic per medallia request
--2024-09-10 - switching source table for hosted data and revising joins
--2024-10-09 - adding DIA tier logic to coalesce if guest subtier is null
--2025-05-29 - changing host_dim join logic to include records with blank host_active_flag
--2025-08-14 - adding join condition to property market lookup to filter out secondary markets
--2026-10-30 - adding ORIGIN_UNIT_ID for HLT/TAH distinction
--2026-11-17 - DAASI-3811 adding LOYALTY (Luxury Experience tag) from the LMS73 hotel reservations fact

TRUNCATE TABLE IF EXISTS DAAS_CORE.MEDALLIA_V_CUSTOMER_INVITATION_HOTEL;

INSERT INTO DAAS_CORE.MEDALLIA_V_CUSTOMER_INVITATION_HOTEL(
   TRANSACTION_ID
  ,TRANSACTION_DATE
  ,PROPERTY_MARKET_CD
  ,UNIT_ID
  ,ORIGIN_UNIT_ID
  ,CLUBCARD_YN
  ,CUSTOMER_ID
  ,GUEST_ID
  ,PROP_ID
  ,FIRST_NAME
  ,LAST_NAME
  ,GENDER
  ,EMAIL_ADDRESS
  ,PHONE_NUMBER
  ,Age
  ,CITY_NAME
  ,STATE_PROVINCE_CODE
  ,ZIP_CODE
  ,ZIP_PLUS_4
  ,TIER_CODE
  ,HOTEL_FLAG
  ,CASINO_FLAG
  ,ROOM_NUMBER
  ,RESERVATION_NUMBER
  ,ROOM_TYPE_BOOKED
  ,ROOM_TYPE_RECEIVED
  ,RATE_PLAN_CD
  ,RESERVATION_DATE
  ,RESERVATION_AGENT
  ,CHECK_IN_DATE
  ,CHECK_OUT_DATE
  ,CHECKIN_AGENT_ID
  ,CHECKOUT_AGENT_ID
  ,WING_CD
  ,ROOM_BLOCK_CD
  ,HOTEL_COMP_FLAG_YN
  ,HOST_NAME
  ,HOST_CODE
  ,HOSTED_YN
  ,ADR
  --,PROPERTY_WINLOSS
  ,HOSP_POS_SPEND
  ,ROOM_REV_AMT
  --,THEO_AMT
  ,d_arrival_dt
  ,d_departure_dt
  ,i_checkin_hr
  ,i_checkin_min
  ,LOYALTY
)

WITH HOSP
AS
    (
    SELECT TRIP.GUEST_UNIQUE_ID, TRIP.PROPERTY_CD, TRIP.TRIP_END_DT,
    SUM(TRIP.HOTEL_AMT_TOTAL) AS ROOM_REV_AMT,
    SUM(TRIP.POS_TOTAL_ITEM_AMT) AS HOSP_POS_SPEND
        FROM DAAS_CORE_MARKETING_VW.TRIP_SUMMARY_VW TRIP
        GROUP BY TRIP.GUEST_UNIQUE_ID, TRIP.PROPERTY_CD, TRIP.TRIP_END_DT

    ),

HOSTED_CUST
AS
    (
        SELECT GUEST_UNIQUE_ID, PROPERTY_CD, HOST_CD 
        FROM DAAS_CORE_CUSTOMER_VW.GUEST_XREF_PROP_LOCAL_ACCOUNT_VW
    ),

LOYALTY_TAG
AS
    (
        -- DAASI-3811 Luxury Experience tag, one row per reservation.
        -- LOYALTY is typed by hand in LMS, so only the approved codes listed below are passed to Medallia.
        SELECT PROPERTY_CD, RESERVATION_ID, MAX(TRIM(LOYALTY)) AS LOYALTY
        FROM DAAS_CORE_HOTEL.LMS73_HOTEL_RESERVATIONS_FACT
        WHERE DELETE_IND = ''N''
        AND TRIM(LOYALTY) IN (''LUX'')
        GROUP BY PROPERTY_CD, RESERVATION_ID
    ),

ROOM_REV
AS
    (
        SELECT HOTEL_FOLIO_DETAIL_FACT_VW.PROPERTY_CD
             , HOTEL_FOLIO_DETAIL_FACT_VW.RESERVATION_ID
             , ZEROIFNULL(SUM(HOTEL_FOLIO_DETAIL_FACT_VW.FOLIO_AMT))      AS ROOM_REV
             , SUM(
                    ZEROIFNULL(HOTEL_FOLIO_DETAIL_FACT_VW.TAX_AMOUNT_1) +
                    ZEROIFNULL(HOTEL_FOLIO_DETAIL_FACT_VW.TAX_AMOUNT_2) +
                    ZEROIFNULL(HOTEL_FOLIO_DETAIL_FACT_VW.TAX_AMOUNT_3) +
                    ZEROIFNULL(HOTEL_FOLIO_DETAIL_FACT_VW.TAX_AMOUNT_4) +
                    ZEROIFNULL(HOTEL_FOLIO_DETAIL_FACT_VW.TAX_AMOUNT_5)
                    + ZEROIFNULL(HOTEL_FOLIO_DETAIL_FACT_VW.TAX_AMOUNT_6) +
                    ZEROIFNULL(HOTEL_FOLIO_DETAIL_FACT_VW.TAX_AMOUNT_7) +
                    ZEROIFNULL(HOTEL_FOLIO_DETAIL_FACT_VW.TAX_AMOUNT_8)
            )                                                             AS TAX_AMOUNT
             , SUM(TOTAL_TIP)                                             AS TIP_AMOUNT
             , ROOM_REV - ZEROIFNULL(TAX_AMOUNT) - ZEROIFNULL(TIP_AMOUNT) AS NET_ROOM_REV
        FROM DAAS_CORE_HOTEL_VW.HOTEL_FOLIO_DETAIL_FACT_VW HOTEL_FOLIO_DETAIL_FACT_VW
                 INNER JOIN DAAS_CORE_HOTEL_VW.HOTEL_FOLIO_HEADER_FACT_VW HDR
                            ON HOTEL_FOLIO_DETAIL_FACT_VW.PROPERTY_CD = HDR.PROPERTY_CD
                                AND HOTEL_FOLIO_DETAIL_FACT_VW.FOLIO_ID = HDR.FOLIO_ID
                                AND HOTEL_FOLIO_DETAIL_FACT_VW.RESERVATION_ID = HDR.RESERVATION_ID
                 INNER JOIN DAAS_CORE.DAAS_PROP_ROOM_REV_CONFIG DAAS_PROP_ROOM_REV_CONFIG
                            ON HOTEL_FOLIO_DETAIL_FACT_VW.REVENUE_CENTER_CD =
                               DAAS_PROP_ROOM_REV_CONFIG.REVENUE_CENTER_CD
                                AND HOTEL_FOLIO_DETAIL_FACT_VW.PROPERTY_CD = DAAS_PROP_ROOM_REV_CONFIG.PROPERTY_CD
                 JOIN DAAS_CORE_HOTEL_VW.HOTEL_GUEST_RESERVATIONS_FACT_VW RESV
                      ON HOTEL_FOLIO_DETAIL_FACT_VW.PROPERTY_CD = RESV.PROPERTY_CD
                          AND HOTEL_FOLIO_DETAIL_FACT_VW.RESERVATION_ID = RESV.RESERVATION_ID
                 JOIN (SELECT DATE
                       FROM DAAS_COMMON_VW.DATE_DIM_VW A
                                JOIN (
                           SELECT WEEK_START_DATE, WEEK_END_DATE
                           FROM (
                                    SELECT WEEK_START_DATE
                                         , WEEK_END_DATE
                                         , WEEK_OF_YEAR
                                         , ROW_NUMBER() OVER (ORDER BY WEEK_END_DATE DESC) AS RN
                                   FROM DAAS_COMMON_VW.DATE_DIM_VW
                                    WHERE DATE <= CURRENT_DATE
                                      AND DATE >= CURRENT_DATE - 40
                                    GROUP BY 1, 2, 3
                                )
                                -- RN = 3 = 2 weeks ago
                           WHERE RN = 3
                       ) B
                                     ON A.WEEK_START_DATE = B.WEEK_START_DATE
                                         AND A.WEEK_END_DATE = B.WEEK_END_DATE
        ) DATE_CONTROL
                      ON CAST(RESV.CHECK_OUT_DTTM AS DATE) = DATE_CONTROL.DATE
        WHERE HOTEL_FOLIO_DETAIL_FACT_VW.DELETE_IND = ''N''
          -- exclude settlements
          AND COALESCE(HOTEL_FOLIO_DETAIL_FACT_VW.TICKET_CLASSIFICATION, '''') = ''REVENUE''
          AND HOTEL_FOLIO_DETAIL_FACT_VW.FOLIO_TYPE = 5
        GROUP BY 1, 2
    )

SELECT DISTINCT
TRIP.TRIP_MASTER_ID AS TRANSACTION_ID,
HOTELREV.DEPARTURE_DT AS TRANSACTION_DATE,
PROPLKP.MARKET_CD AS PROPERTY_MARKET_CD,
HOTELREV.PROPERTY_CD AS UNIT_ID,
CASE WHEN HOTELREV.PROPERTY_CD = ''TAH'' AND HOTELREV.WING_CD = ''CT'' THEN ''HLT'' ELSE NULL END AS ORIGIN_UNIT_ID,
CASE WHEN GST.GUEST_ACCOUNT_TYPE_CD = ''TRV'' THEN ''Y'' ELSE ''N'' END AS CLUBCARD_YN,
HOTELREV.GUEST_UNIQUE_ID AS CUSTOMER_ID,
GST.GUEST_ID AS GUEST_ID,
GST.PROPERTY_ID AS PROP_ID,
GST.GUEST_FIRST_NM AS FIRST_NAME,
GST.GUEST_LAST_NM AS LAST_NAME,
COALESCE(GST.GUEST_GENDER, '''') AS GENDER,
COALESCE(EML.GUEST_EMAIL, '''') AS EMAIL_ADDRESS,
COALESCE(TEL.TELEPHONE_NBR, ''0'')  AS PHONE_NUMBER,
CASE WHEN GST.GUEST_DATE_OF_BIRTH = ''12/31/1899'' THEN ''N/A'' ELSE CAST(DATEDIFF(DAY, GST.GUEST_DATE_OF_BIRTH::DATE, CURRENT_DATE())/365.25 AS INT)::VARCHAR(5) END AS Age,
COALESCE(ADDR.GUEST_CITY, '''') AS CITY_NAME,
COALESCE(ADDR.GUEST_STATE_CD, '''') AS STATE_PROVINCE_CODE,
COALESCE(SUBSTR(ADDR.GUEST_ZIP_CD, 1, 5), '''') AS ZIP_CODE,
COALESCE(SUBSTR(ADDR.GUEST_ZIP_CD, 6, 4), '''') AS ZIP_PLUS_4,
CASE WHEN TIER.TIER_CD = ''DIA'' THEN COALESCE(CONCAT(TIER.TIER_CD, ''-'', SUB.SUBTIER_CD), TIER.TIER_CD) ELSE TIER.TIER_CD END AS TIER_CODE,
COALESCE(TRIP.HOTEL_FLG,'''') AS HOTEL_FLAG,
COALESCE(TRIP.GAMING_FLG,'''') AS CASINO_FLAG,
COALESCE(HOTELREV.ROOM_NBR,'''') AS ROOM_NUMBER,
CAST(CAST(HOTELREV.RESERVATION_ID AS BIGINT) AS VARCHAR(12)) AS RESERVATION_NUMBER,
COALESCE(HOTELRM.ROOM_TYPE_ID,'''') AS ROOM_TYPE_BOOKED,
COALESCE(HOTELREV.ACCOMMODATION_TYPE,'''') AS ROOM_TYPE_RECEIVED,
HOTELREV.RATE_PLAN AS RATE_PLAN_CD,
HOTELREV.DATE_RESERVATION_MADE AS RESERVATION_DATE,
COALESCE(HOTELREV.RESERVATIONS_AGENT,'''') AS RESERVATION_AGENT,
HOTELREV.ARRIVAL_DT AS CHECK_IN_DATE,
HOTELREV.DEPARTURE_DT AS CHECK_OUT_DATE,
HOTELREV.CHECK_IN_AGENT AS CHECKIN_AGENT_ID,
HOTELREV.CHECK_OUT_AGENT AS CHECKOUT_AGENT_ID,
HOTELREV.WING_CD AS WING_CD,
COALESCE(HOTELREV.GROUP_CD,'''') AS ROOM_BLOCK_CD,
CASE WHEN zeroifnull(TRIP.HOTEL_COMP_ROOM_AMT + TRIP.HOTEL_COMP_TKT_FOOD_BEVERAGE_AMT + TRIP.HOTEL_COMP_OTHER_AMT) > 0 THEN ''Y'' ELSE ''N'' END AS HOTEL_COMP_FLAG_YN,
COALESCE(HOST.HOST_NAME,'''') AS HOST_NAME,
CASE WHEN COALESCE(HOST.HOST_ID,'''') <> ''''
    THEN TRIM(HOST.PROPERTY_CD) || TRIM(HOST.HOST_ID)
    ELSE '''' END AS HOST_CODE,
CASE WHEN COALESCE(HOST.HOST_NAME,'''') <> '''' THEN ''Y'' ELSE ''N'' END AS HOSTED_YN,
COALESCE(HOTELREV.ROOM_RT, 0) AS ADR,
--COALESCE(TRIP.TOTAL_WIN_LOSS_AMT,0) AS PROPERTY_WINLOSS,
COALESCE(TRIP.POS_TAXABLE_SALES_AMT,0) AS HOSP_POS_SPEND,
COALESCE(REVENUE.NET_ROOM_REV,0) AS ROOM_REV_AMT,
--COALESCE(TRIP.TOTAL_THEO_WIN_AMT,0) AS THEO_AMT,
HOTELREV.ARRIVAL_DT AS d_arrival_dt,
HOTELREV.DEPARTURE_DT AS d_departure_dt,
HOUR(HOTELREV.CHECK_IN_DTTM) AS i_checkin_hr,
MINUTE(HOTELREV.CHECK_IN_DTTM) AS i_checkin_min,
LUX.LOYALTY AS LOYALTY


FROM DAAS_CORE_HOTEL_VW.HOTEL_GUEST_RESERVATIONS_FACT_VW HOTELREV
    INNER JOIN DAAS_CORE_MARKETING_VW.TRIP_SUMMARY_VW TRIP
        ON TRIP.GUEST_UNIQUE_ID = HOTELREV.GUEST_UNIQUE_ID
        AND TRIP.PROPERTY_CD = HOTELREV.PROPERTY_CD
        AND TRIP.TRIP_END_DT BETWEEN HOTELREV.ARRIVAL_DT AND HOTELREV.DEPARTURE_DT
        --AND TRIP.MARKET_CD = PROPLKP.MARKET_CD
        AND TRIP.TRIP_TYPE = ''PROPERTY''
    INNER JOIN DAAS_CORE.GUEST_DIM GST
        ON HOTELREV.GUEST_UNIQUE_ID = GST.GUEST_UNIQUE_ID
        --AND GST.ACTIVE_FLG = ''Y'' --NOT PRESENT IN DEV, CANT DEPLOY WITH THIS FLAG
        AND GST.DELETE_IND = ''N''
    LEFT JOIN DAAS_CORE.GUEST_EMAIL_DIM EML
        ON HOTELREV.GUEST_UNIQUE_ID = EML.GUEST_UNIQUE_ID
        AND EML.ACTIVE_FLG = ''Y''
        AND EML.DELETE_IND = ''N''
    LEFT JOIN DAAS_CORE.GUEST_TELEPHONE_DIM TEL
        ON HOTELREV.GUEST_UNIQUE_ID = TEL.GUEST_UNIQUE_ID
        AND GST.GUEST_ADDRESS_TYPE = TEL.PHONE_TYPE
        AND TEL.ACTIVE_FLG = ''Y''
        AND TEL.DELETE_IND = ''N''
        AND TEL.TELEPHONE_NBR != ''''
    LEFT JOIN DAAS_CORE.GUEST_ADDRESS_DIM ADDR
        ON HOTELREV.GUEST_UNIQUE_ID = ADDR.GUEST_UNIQUE_ID
        AND GST.GUEST_ADDRESS_TYPE = ADDR.GUEST_ADDRESS_TYPE
        AND ADDR.ACTIVE_FLG = ''Y''
        AND ADDR.DELETE_IND = ''N''
    LEFT JOIN DAAS_CORE.GUEST_SUBTIER_DIM SUB
        ON HOTELREV.GUEST_UNIQUE_ID = SUB.GUEST_UNIQUE_ID
        AND SUB.DELETE_IND = ''N''
    LEFT JOIN DAAS_CORE.GUEST_TIER_DIM TIER
        ON HOTELREV.GUEST_UNIQUE_ID = TIER.GUEST_UNIQUE_ID
        AND TIER.DELETE_IND = ''N''
    LEFT JOIN DAAS_COMMON.PROPERTY_MARKET_LKP PROPLKP
        ON HOTELREV.PROPERTY_CD = PROPLKP.PROPERTY_CD
        AND PROPLKP.SECONDARY_MARKET_FLG = ''N''
    LEFT JOIN ROOM_REV REVENUE
        ON HOTELREV.RESERVATION_ID = REVENUE.RESERVATION_ID
        AND HOTELREV.PROPERTY_CD = REVENUE.PROPERTY_CD
    LEFT JOIN HOSTED_CUST HOSTCUS
        ON GST.GUEST_UNIQUE_ID = HOSTCUS.GUEST_UNIQUE_ID
        AND HOTELREV.PROPERTY_CD = HOSTCUS.PROPERTY_CD
        --AND GST.GUEST_FIRST_DOMINANT_CD = HOSTCUS.PROPERTY_CD
    LEFT JOIN DAAS_CORE.HOST_DIM HOST
        ON HOSTCUS.HOST_CD = HOST.HOST_ID
        AND HOSTCUS.PROPERTY_CD = HOST.PROPERTY_CD
        AND HOST.ACTIVE_FLG = ''Y''
        AND HOST.HOST_ACTIVE_FLG <> ''N''
        AND HOST.DELETE_IND = ''N''
    LEFT JOIN DAAS_CORE_HOTEL_VW.HOTEL_ROOMS_DIM_VW HOTELRM
        ON HOTELREV.ROOM_NBR = HOTELRM.ROOM_NBR
        AND HOTELREV.WING_CD = HOTELRM.WING_CD
        AND HOTELREV.PROPERTY_CD = HOTELRM.PROPERTY_CD
        AND HOTELRM.ACTIVE_FLG = ''Y''
        AND HOTELRM.DELETE_IND = ''N''
    LEFT JOIN HOSP
        ON TRIP.GUEST_UNIQUE_ID = HOSP.GUEST_UNIQUE_ID
        AND TRIP.PROPERTY_CD = HOSP.PROPERTY_CD
        AND TRIP.TRIP_END_DT = HOSP.TRIP_END_DT
    LEFT JOIN DAAS_CORE.GUEST_PROPERTY_MAIL_CODE_DIM MAILCODES
        ON GST.GUEST_UNIQUE_ID = MAILCODES.GUEST_UNIQUE_ID
        AND MAILCODES.ACTIVE_FLG = ''Y''
        AND MAILCODES.DELETE_IND = ''N''
    LEFT JOIN LOYALTY_TAG LUX
        ON HOTELREV.PROPERTY_CD = LUX.PROPERTY_CD
        AND HOTELREV.RESERVATION_ID = LUX.RESERVATION_ID



WHERE ADDR.GUEST_COUNTRY_CD IN (''USA'', ''CAN'')
AND HOTELREV.RESERVATION_STATUS_CD != ''X''
AND COALESCE(EML.EMAIL_OPT_IN_FLAG, ''Y'') = ''Y''
AND COALESCE(MAILCODES.PROPERTY_MAIL_CD, ''100'') < ''300''
AND CHECK_OUT_DATE = :RUNDATE;
--ERI PROPS
--AND HOTELREV.PROPERTY_CD NOT IN (''TGV'', ''IBV'', ''ILU'', ''IWA'');

--RETURN ''Inserted '' || SQLROWCOUNT || '' rows.'';

RETURN ''Finished Calling Stored Procedure'';
END';
