GROUP BY CHECKED_ROWS
ORDER BY CHECKED_ROWS;


-- ===========================================================================================================
-- VALIDATION 3. The tables gain one column, at the end. Reads table definitions only; needs no set-up.
-- ===========================================================================================================

-- The five Medallia tables in UAT, where the change is deployed, against the same tables in PROD today.
--   UNCHANGED_COLUMNS: columns with the same name, the same position and the same type in both.
--   CHANGED_OR_MISSING_IN_UAT: PROD columns that UAT lacks or holds in another position or type. Expect (none).
--   PASS = every PROD column is unchanged in UAT, and UAT has one more: LOYALTY, in the last position.
-- The export tasks send every column of the two file tables in table order, so this is also what happens to the
-- daily files: the same columns in the same order, plus LOYALTY at the end.
-- It reads the column catalogue of both databases and took about seven minutes on 11/21.
WITH PROD_COLS AS (
    SELECT TABLE_SCHEMA, TABLE_NAME, COLUMN_NAME, ORDINAL_POSITION, DATA_TYPE
    FROM DAAS_PROD.INFORMATION_SCHEMA.COLUMNS
    WHERE (TABLE_SCHEMA = 'DAAS_CORE' AND TABLE_NAME IN ('MEDALLIA_V_CUSTOMER_INVITATION_HOTEL',
                                                     'MEDALLIA_V_CUSTOMER_INVITATION_COMPLETE',
                                                     'MEDALLIA_V_CUSTOMER_INVITATION_ARCHIVE'))
    OR    (TABLE_SCHEMA = 'HPDB'      AND TABLE_NAME IN ('MEDALLIA_PROSPECT_INVITATION_FILE',
                                                     'MEDALLIA_PROSPECT_INVITATION_FILE_ARCHIVE'))
),
UAT_COLS AS (
    SELECT TABLE_SCHEMA, TABLE_NAME, COLUMN_NAME, ORDINAL_POSITION, DATA_TYPE
    FROM DAAS_UAT.INFORMATION_SCHEMA.COLUMNS
    WHERE (TABLE_SCHEMA = 'DAAS_CORE' AND TABLE_NAME IN ('MEDALLIA_V_CUSTOMER_INVITATION_HOTEL',
                                                     'MEDALLIA_V_CUSTOMER_INVITATION_COMPLETE',
                                                     'MEDALLIA_V_CUSTOMER_INVITATION_ARCHIVE'))
    OR    (TABLE_SCHEMA = 'HPDB'      AND TABLE_NAME IN ('MEDALLIA_PROSPECT_INVITATION_FILE',
                                                     'MEDALLIA_PROSPECT_INVITATION_FILE_ARCHIVE'))
),
COMPARED AS (
    SELECT NVL(P.TABLE_SCHEMA, U.TABLE_SCHEMA) || '.' || NVL(P.TABLE_NAME, U.TABLE_NAME) AS TABLE_NAME,
           COUNT(P.COLUMN_NAME) AS COLUMNS_IN_PROD,
           COUNT(U.COLUMN_NAME) AS COLUMNS_IN_UAT,
           COUNT_IF(P.ORDINAL_POSITION = U.ORDINAL_POSITION AND P.DATA_TYPE = U.DATA_TYPE) AS UNCHANGED_COLUMNS,
           NVL(NULLIF(LISTAGG(IFF(P.COLUMN_NAME IS NULL, U.COLUMN_NAME, NULL), ', '), ''), '(none)') AS ADDED_IN_UAT,
           MAX(IFF(P.COLUMN_NAME IS NULL, U.ORDINAL_POSITION, NULL)) AS ADDED_AT_POSITION,
           NVL(NULLIF(LISTAGG(IFF(U.COLUMN_NAME IS NULL OR P.ORDINAL_POSITION <> U.ORDINAL_POSITION OR P.DATA_TYPE <> U.DATA_TYPE,
                                  P.COLUMN_NAME, NULL), ', '), ''), '(none)') AS CHANGED_OR_MISSING_IN_UAT
    FROM PROD_COLS P
    FULL OUTER JOIN UAT_COLS U
        ON U.TABLE_SCHEMA = P.TABLE_SCHEMA
        AND U.TABLE_NAME = P.TABLE_NAME
        AND U.COLUMN_NAME = P.COLUMN_NAME
    GROUP BY 1
)
SELECT TABLE_NAME,
       COLUMNS_IN_PROD,
       COLUMNS_IN_UAT,
       UNCHANGED_COLUMNS,
       ADDED_IN_UAT,
       ADDED_AT_POSITION,
       CHANGED_OR_MISSING_IN_UAT,
       IFF(COLUMNS_IN_PROD > 0 AND UNCHANGED_COLUMNS = COLUMNS_IN_PROD AND COLUMNS_IN_UAT = COLUMNS_IN_PROD + 1
           AND ADDED_IN_UAT = 'LOYALTY' AND ADDED_AT_POSITION = COLUMNS_IN_UAT AND CHANGED_OR_MISSING_IN_UAT = '(none)',
           'PASS', 'INVESTIGATE') AS RESULT
FROM COMPARED
ORDER BY TABLE_NAME;


-- ===========================================================================================================
-- VALIDATION 4. Nothing else is affected. Reads Snowflake's own records of what depends on what; needs no set-up.
-- ===========================================================================================================

-- A table that gains a column keeps working for everything that names its columns. The one thing that breaks is
-- a view written as SELECT * over it: Snowflake fixes such a view's columns when it is created, and it returns an
-- error once the table has one more. So this lists everything else in PROD that reads the five tables.
--   Line 1 of the search: views, dynamic tables, streams and the like that Snowflake records as built on them.
--   Line 2 of the search: procedures whose text names them, other than the three this change replaces.
--   PASS = nothing else reads the table. REVIEW = something does, and its name is listed.
-- REVIEW is not a failure. Send me the result and we check each name: an object that lists its columns is not
-- affected. (Tasks are not in these records. The eight Medallia tasks are the known ones: the two archive tasks
-- are part of this change, and the export tasks send every column, which is how the new one reaches the files.)
-- If Snowflake says OBJECT_DEPENDENCIES does not exist or is not authorized, this role cannot read that record:
-- tell me and I will write the check another way.
WITH TABLES_CHANGED AS (
    SELECT 'DAAS_CORE' AS TABLE_SCHEMA, 'MEDALLIA_V_CUSTOMER_INVITATION_HOTEL' AS TABLE_NAME
    UNION ALL SELECT 'DAAS_CORE', 'MEDALLIA_V_CUSTOMER_INVITATION_COMPLETE'
    UNION ALL SELECT 'DAAS_CORE', 'MEDALLIA_V_CUSTOMER_INVITATION_ARCHIVE'
    UNION ALL SELECT 'HPDB', 'MEDALLIA_PROSPECT_INVITATION_FILE'
    UNION ALL SELECT 'HPDB', 'MEDALLIA_PROSPECT_INVITATION_FILE_ARCHIVE'
),
READERS AS (
    SELECT T.TABLE_SCHEMA,
           T.TABLE_NAME,
           D.REFERENCING_OBJECT_DOMAIN || ' ' || D.REFERENCING_DATABASE || '.' || D.REFERENCING_SCHEMA || '.' ||
               D.REFERENCING_OBJECT_NAME AS READER
    FROM TABLES_CHANGED T
    JOIN SNOWFLAKE.ACCOUNT_USAGE.OBJECT_DEPENDENCIES D
        ON D.REFERENCED_DATABASE = 'DAAS_PROD'
        AND D.REFERENCED_SCHEMA = T.TABLE_SCHEMA
        AND D.REFERENCED_OBJECT_NAME = T.TABLE_NAME
    UNION
    SELECT T.TABLE_SCHEMA,
           T.TABLE_NAME,
           'PROCEDURE ' || P.PROCEDURE_CATALOG || '.' || P.PROCEDURE_SCHEMA || '.' || P.PROCEDURE_NAME
    FROM TABLES_CHANGED T
    JOIN SNOWFLAKE.ACCOUNT_USAGE.PROCEDURES P
        ON CONTAINS(UPPER(P.PROCEDURE_DEFINITION), T.TABLE_NAME)
    WHERE P.DELETED IS NULL
    AND P.PROCEDURE_CATALOG = 'DAAS_PROD'
    AND NOT (P.PROCEDURE_SCHEMA = 'DAAS_COMMON' AND P.PROCEDURE_NAME IN ('MEDALLIA_V_CUSTOMER_INVITATION_HOTEL_PROC',
                                                                        'MEDALLIA_V_CUSTOMER_INVITATION_COMPLETE_PROC'))
    AND NOT (P.PROCEDURE_SCHEMA = 'HPDB' AND P.PROCEDURE_NAME = 'MEDALLIA_PROSPECT_INVITATION_FILE_PROC')
)
SELECT T.TABLE_SCHEMA || '.' || T.TABLE_NAME AS TABLE_NAME,
       COUNT(R.READER) AS OTHER_OBJECTS_THAT_READ_IT,
       NVL(NULLIF(LISTAGG(R.READER, ', '), ''), '(none)') AS WHICH_ONES,
       IFF(COUNT(R.READER) = 0, 'PASS', 'REVIEW') AS RESULT
FROM TABLES_CHANGED T
LEFT JOIN READERS R
    ON R.TABLE_SCHEMA = T.TABLE_SCHEMA
    AND R.TABLE_NAME = T.TABLE_NAME
GROUP BY 1
ORDER BY 1;


-- ===========================================================================================================
-- VALIDATION 4, STEP 2. How each object that step 1 listed reads the tables. Needs no set-up.
-- ===========================================================================================================

-- One line for every object that step 1 listed, with three counts taken from its own text.
--   ASTERISKS: asterisks in its text, COUNT(*) aside. With none, it cannot hold a SELECT * of any kind, so it
--   names every column it reads.
--   INSERTS and INSERTS_NAMING_COLUMNS: how many INSERT statements it has, and how many of those list the
--   columns they fill.
--   NOT AFFECTED = no asterisk, and every insert lists its columns. An object like that reads and writes the same
--   columns after a table gains one, so the new column cannot reach it or break it.
--   LOOK = one of those is not so, which can be harmless (an asterisk used to multiply, the word insert in a
--   comment). TEXT NOT SHOWN = this role is not shown the object's text. Send me the result for either.
-- LAST_CHANGED is the day the object was last altered.
WITH TABLES_CHANGED AS (
    SELECT 'DAAS_CORE' AS TABLE_SCHEMA, 'MEDALLIA_V_CUSTOMER_INVITATION_HOTEL' AS TABLE_NAME
    UNION ALL SELECT 'DAAS_CORE', 'MEDALLIA_V_CUSTOMER_INVITATION_COMPLETE'
    UNION ALL SELECT 'DAAS_CORE', 'MEDALLIA_V_CUSTOMER_INVITATION_ARCHIVE'
    UNION ALL SELECT 'HPDB', 'MEDALLIA_PROSPECT_INVITATION_FILE'
    UNION ALL SELECT 'HPDB', 'MEDALLIA_PROSPECT_INVITATION_FILE_ARCHIVE'
),
LISTED_IN_STEP_1 AS (
    SELECT DISTINCT D.REFERENCING_OBJECT_DOMAIN AS OBJECT_KIND,
           D.REFERENCING_DATABASE AS OBJECT_DATABASE,
           D.REFERENCING_SCHEMA AS OBJECT_SCHEMA,
           D.REFERENCING_OBJECT_NAME AS OBJECT_NAME
    FROM TABLES_CHANGED T
    JOIN SNOWFLAKE.ACCOUNT_USAGE.OBJECT_DEPENDENCIES D
        ON D.REFERENCED_DATABASE = 'DAAS_PROD'
        AND D.REFERENCED_SCHEMA = T.TABLE_SCHEMA
        AND D.REFERENCED_OBJECT_NAME = T.TABLE_NAME
),
OBJECT_TEXT AS (
    SELECT L.OBJECT_KIND || ' ' || L.OBJECT_DATABASE || '.' || L.OBJECT_SCHEMA || '.' || L.OBJECT_NAME AS LISTED_OBJECT,
           V.LAST_ALTERED AS LAST_ALTERED,
           V.VIEW_DEFINITION AS FULL_TEXT
    FROM LISTED_IN_STEP_1 L
    LEFT JOIN SNOWFLAKE.ACCOUNT_USAGE.VIEWS V
        ON V.TABLE_CATALOG = L.OBJECT_DATABASE
        AND V.TABLE_SCHEMA = L.OBJECT_SCHEMA
        AND V.TABLE_NAME = L.OBJECT_NAME
        AND V.DELETED IS NULL
    UNION ALL
    SELECT DISTINCT 'PROCEDURE ' || P.PROCEDURE_CATALOG || '.' || P.PROCEDURE_SCHEMA || '.' || P.PROCEDURE_NAME,
           P.LAST_ALTERED,
           P.PROCEDURE_DEFINITION
    FROM TABLES_CHANGED T
    JOIN SNOWFLAKE.ACCOUNT_USAGE.PROCEDURES P
        ON CONTAINS(UPPER(P.PROCEDURE_DEFINITION), T.TABLE_NAME)
    WHERE P.DELETED IS NULL
    AND P.PROCEDURE_CATALOG = 'DAAS_PROD'
    AND NOT (P.PROCEDURE_SCHEMA = 'DAAS_COMMON' AND P.PROCEDURE_NAME IN ('MEDALLIA_V_CUSTOMER_INVITATION_HOTEL_PROC',
                                                                        'MEDALLIA_V_CUSTOMER_INVITATION_COMPLETE_PROC'))
    AND NOT (P.PROCEDURE_SCHEMA = 'HPDB' AND P.PROCEDURE_NAME = 'MEDALLIA_PROSPECT_INVITATION_FILE_PROC')
),
ON_ONE_LINE AS (
    SELECT LISTED_OBJECT,
           TO_DATE(LAST_ALTERED) AS LAST_CHANGED,
           TRANSLATE(FULL_TEXT, CHAR(9) || CHAR(10) || CHAR(13), '   ') AS FLAT_TEXT
    FROM OBJECT_TEXT
),
COUNTED AS (
    SELECT LISTED_OBJECT,
           LAST_CHANGED,
           REGEXP_COUNT(FLAT_TEXT, '[*]') - REGEXP_COUNT(FLAT_TEXT, 'COUNT *[(] *[*] *[)]', 1, 'i') AS ASTERISKS,
           REGEXP_COUNT(FLAT_TEXT, 'INSERT ', 1, 'i') AS INSERTS,
           REGEXP_COUNT(FLAT_TEXT,
                        'INSERT +(OVERWRITE +)?INTO +[A-Za-z0-9_.]+ *[(] *[A-Za-z0-9_"]+ *[,)]',
                        1, 'i') AS INSERTS_NAMING_COLUMNS
    FROM ON_ONE_LINE
)
SELECT LISTED_OBJECT,
       LAST_CHANGED,
       ASTERISKS,
       INSERTS,
       INSERTS_NAMING_COLUMNS,
       IFF(ASTERISKS IS NULL, 'TEXT NOT SHOWN',
           IFF(ASTERISKS = 0 AND INSERTS = INSERTS_NAMING_COLUMNS, 'NOT AFFECTED', 'LOOK')) AS RESULT
FROM COUNTED
ORDER BY LISTED_OBJECT;


