-- Every row is looked up in LMS (the LMS73 hotel reservations fact) by property and reservation number.
--   TAGGED_LUX:  rows that carry LUX in the new column.
--   LUX_IN_LMS:  rows whose reservation LMS codes LUX.
--   MISMATCHES:  rows where the two disagree, either way.
--   PASS = no mismatch. Expect TAGGED_LUX = LUX_IN_LMS = 3 on lines 1 and 3, 0 on line 2, 4 on line 4.
-- Lines 1 to 3 read the new code's output for 11/16. Line 3 is the archive task's own statement.
-- Line 4 is the prospect file. Its procedure cannot return rows under this role (see the top of this script),
-- so the new code's lookup (transaction to hotel reservation to LMS, joined as the new procedure joins them)
-- is applied to every row the real task sent on 10/30, 11/06 and 11/11, the three days since 10/21 on which a
-- prospect row belonged to a Luxury Experience stay. A prospect is a guest with no Caesars Rewards account.
WITH LUX AS (
    SELECT PROPERTY_CD, RESERVATION_ID, MAX(TRIM(LOYALTY)) AS LOYALTY
    FROM DAAS_PROD.DAAS_CORE_HOTEL.LMS73_HOTEL_RESERVATIONS_FACT
    WHERE DELETE_IND = 'N'
    AND TRIM(LOYALTY) IN ('LUX')
    GROUP BY PROPERTY_CD, RESERVATION_ID
),
PROSPECT_LOOKUP AS (
    SELECT FCT.TRANSACTION_DT::DATE AS RUN_DAY,
           FCT.PROPERTY_CD AS UNIT_ID,
           TO_VARCHAR(FCT.RESERVATION_ID) AS RESERVATION_NUMBER,
           MAX(LUX.LOYALTY) AS LOYALTY
    FROM DAAS_PROD.HPDB.PROSPECT_TRANSACTION_FACT FCT
    LEFT JOIN DAAS_PROD.DAAS_CORE_HOTEL_VW.HOTEL_GUEST_RESERVATIONS_FACT_VW RESV
        ON FCT.RESERVATION_ID = TO_VARCHAR(RESV.RESERVATION_ID)
        AND FCT.PROPERTY_CD = RESV.PROPERTY_CD
    LEFT JOIN LUX
        ON RESV.RESERVATION_ID = LUX.RESERVATION_ID
        AND RESV.PROPERTY_CD = LUX.PROPERTY_CD
    WHERE FCT.TRANSACTION_DT IN ('2026-10-30'::DATE, '2026-11-06'::DATE, '2026-11-11'::DATE)
    AND FCT.SOURCE_SYSTEM_NM = 'HOTEL'
    GROUP BY 1, 2, 3
),
CHECKED AS (
    SELECT IFF(NVL(F.RESERVATION_NUMBER, '') = '',
               '2 Invitation file, gaming-only rows',
               '1 Invitation file, hotel-stay rows') AS CHECKED_ROWS,
