           LUX.LOYALTY
    FROM DAAS_PROD.DAAS_TEMP_WORK.T3811_NEW_INVITATION_ARCHIVE A
    LEFT JOIN LUX
        ON LUX.PROPERTY_CD = A.UNIT_ID
        AND LUX.RESERVATION_ID = TRY_TO_NUMBER(A.RESERVATION_NUMBER)
    UNION ALL
    SELECT '4 Prospect file, rows sent on the three days',
           N.LOYALTY,
           LUX.LOYALTY
    FROM DAAS_PROD.HPDB.MEDALLIA_PROSPECT_INVITATION_FILE_ARCHIVE S
