-- The old code and the new code, same PROD data, stays that checked out 11/16.
--   ROWS_OLD_CODE and ROWS_NEW_CODE: how many rows each version produced.
--   ONLY_IN_OLD and ONLY_IN_NEW: rows one version produced and the other did not.
--   PASS = the same number of rows, and no row on one side only.
-- Lines 1 and 2 compare every existing column, value for value (every column except the new one).
-- Line 3 compares gaming-only rows by guest. A gaming-only row is a guest who played and had no hotel stay.
-- When such a guest has two ratings tied for the day's highest theo (the casino's expected win from the play),
-- the existing code keeps either one, so two runs of the very same code can differ in the other columns. A guest
-- or two apart on line 3 would be that tie-break and not the change; it has not happened in three earlier runs.
WITH OLD_HOTEL  AS (SELECT * EXCLUDE (LOYALTY) FROM DAAS_PROD.DAAS_TEMP_WORK.T3811_OLD_INVITATION_HOTEL),
     NEW_HOTEL  AS (SELECT * EXCLUDE (LOYALTY) FROM DAAS_PROD.DAAS_TEMP_WORK.T3811_NEW_INVITATION_HOTEL),
     OLD_STAYS  AS (SELECT * EXCLUDE (LOYALTY) FROM DAAS_PROD.DAAS_TEMP_WORK.T3811_OLD_INVITATION_COMPLETE
                    WHERE NVL(RESERVATION_NUMBER, '') <> ''),
     NEW_STAYS  AS (SELECT * EXCLUDE (LOYALTY) FROM DAAS_PROD.DAAS_TEMP_WORK.T3811_NEW_INVITATION_COMPLETE
                    WHERE NVL(RESERVATION_NUMBER, '') <> ''),
     OLD_GAMING AS (SELECT CUSTOMER_ID FROM DAAS_PROD.DAAS_TEMP_WORK.T3811_OLD_INVITATION_COMPLETE
                    WHERE NVL(RESERVATION_NUMBER, '') = ''),
     NEW_GAMING AS (SELECT CUSTOMER_ID FROM DAAS_PROD.DAAS_TEMP_WORK.T3811_NEW_INVITATION_COMPLETE
                    WHERE NVL(RESERVATION_NUMBER, '') = ''),
     COUNTS AS (
         SELECT '1 Hotel stays table: every existing column' AS COMPARED,
                (SELECT COUNT(*) FROM OLD_HOTEL) AS ROWS_OLD_CODE,
                (SELECT COUNT(*) FROM NEW_HOTEL) AS ROWS_NEW_CODE,
                (SELECT COUNT(*) FROM (SELECT * FROM OLD_HOTEL MINUS SELECT * FROM NEW_HOTEL)) AS ONLY_IN_OLD,
                (SELECT COUNT(*) FROM (SELECT * FROM NEW_HOTEL MINUS SELECT * FROM OLD_HOTEL)) AS ONLY_IN_NEW
         UNION ALL
         SELECT '2 Invitation file, hotel-stay rows: every existing column',
                (SELECT COUNT(*) FROM OLD_STAYS),
                (SELECT COUNT(*) FROM NEW_STAYS),
                (SELECT COUNT(*) FROM (SELECT * FROM OLD_STAYS MINUS SELECT * FROM NEW_STAYS)),
                (SELECT COUNT(*) FROM (SELECT * FROM NEW_STAYS MINUS SELECT * FROM OLD_STAYS))
         UNION ALL
         SELECT '3 Invitation file, gaming-only rows: same guests',
                (SELECT COUNT(*) FROM OLD_GAMING),
                (SELECT COUNT(*) FROM NEW_GAMING),
                (SELECT COUNT(*) FROM (SELECT * FROM OLD_GAMING MINUS SELECT * FROM NEW_GAMING)),
                (SELECT COUNT(*) FROM (SELECT * FROM NEW_GAMING MINUS SELECT * FROM OLD_GAMING))
     )
SELECT COMPARED,
       ROWS_OLD_CODE,
       ROWS_NEW_CODE,
       ONLY_IN_OLD,
       ONLY_IN_NEW,
       IFF(ROWS_NEW_CODE > 0 AND ROWS_OLD_CODE = ROWS_NEW_CODE AND ONLY_IN_OLD = 0 AND ONLY_IN_NEW = 0,
           'PASS', 'INVESTIGATE') AS RESULT
FROM COUNTS
ORDER BY COMPARED;


