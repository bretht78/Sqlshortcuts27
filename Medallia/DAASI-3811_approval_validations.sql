           LUX.LOYALTY AS LMS_TAG
    FROM DAAS_PROD.DAAS_TEMP_WORK.T3811_NEW_INVITATION_COMPLETE F
    LEFT JOIN LUX
        ON LUX.PROPERTY_CD = F.UNIT_ID
        AND LUX.RESERVATION_ID = TRY_TO_NUMBER(F.RESERVATION_NUMBER)
