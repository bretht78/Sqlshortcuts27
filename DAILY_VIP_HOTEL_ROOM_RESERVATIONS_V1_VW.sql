-- DAASI-3864 TECHNICAL DEPLOYMENT COPY (V1). Identical to DAILY_VIP_HOTEL_ROOM_RESERVATIONS_VW.sql except the
-- view name. It exists so the enhancement can be validated in PROD against live data beside the current view.
-- Drop it (and remove this file from the repo) once validated; the real view deploys on deployment day.
--
-- DAASI-3864: add TRACKING_CD and LOYALTY to the VIP dashboard view. DAASI-3314 columns and logic are unchanged.
--
--   TRACKING_CD  LMS reservation TC# (GIP field REF1GI, loaded as REFERENCE_ACCOUNT_1). Taken from the
--                HOTEL_GUEST_RESERVATIONS_FACT_VW join the view already has, so it is populated for the same
--                rows as CONV_CODE and does not depend on the newer LMS73 fact.
--   LOYALTY      LMS reservation Loyalty (LMGEP field FGI1GE). Only HOTEL_RESERVATIONS_VW carries it (DAASI-3810),
--                so this adds one LEFT JOIN to it, on the same keys the existing fact join uses.
--                Checked 2026-11-05: HOTEL_RESERVATIONS_VW has at most one row per RESERVATION_ID + PROPERTY_CD
--                + ARRIVAL_DT, so the join cannot multiply rows, and a LEFT JOIN cannot drop any.
--
--   Blank codes come back as NULL, so "LMS left it blank" and "no fact row" look the same to the dashboard.
--   New columns are appended after TIER_CD so existing column positions do not move.

CREATE OR REPLACE VIEW DAAS_CORE_HOTEL.DAILY_VIP_HOTEL_ROOM_RESERVATIONS_V1_VW AS
SELECT
    VIP_AWARD_TIER_TAG.PROPERTY_CD
    ,VIP_AWARD_TIER_TAG.ARRIVAL_DT
    ,VIP_AWARD_TIER_TAG.DEPARTURE_DT
    ,LEFT(GUEST_DIM_VW.GUEST_FIRST_NM,1) AS FIRST_INITIAL
    ,LEFT(GUEST_DIM_VW.GUEST_LAST_NM,1) AS LAST_INITIAL
    ,HOTEL_CONFIRMATION_VW.CONFIRMATION_NBR
    ,VIP_AWARD_TIER_TAG.RESERVATION_ID
    ,VIP_AWARD_TIER_TAG.RESERVATION_STATUS_CD
    ,VIP_AWARD_TIER_TAG.RATE_PLAN
    ,HOTEL_GUEST_RESERVATIONS_FACT_VW.GROUP_CD AS CONV_CODE
    ,VIP_AWARD_TIER_TAG.WING_CD
    ,VIP_AWARD_TIER_TAG.ROOM_TYPE
    ,VIP_AWARD_TIER_TAG.ROOM_NBR
    ,VIP_AWARD_TIER_TAG.GUEST_UNIQUE_ID
    ,COALESCE(GUEST_TIERSCORE_DIM_VW.TIER_SCORE,0) AS TIER_CREDIT_AMOUNT
    ,GUEST_TIER_DIM_VW.TIER_CD
    ,NULLIF(TRIM(HOTEL_GUEST_RESERVATIONS_FACT_VW.REFERENCE_ACCOUNT_1),'') AS TRACKING_CD   -- DAASI-3864
    ,NULLIF(TRIM(HOTEL_RESERVATIONS_VW.LOYALTY),'') AS LOYALTY                                -- DAASI-3864
FROM (
    SELECT
        PROPERTY_CD
        ,ARRIVAL_DT
        ,DEPARTURE_DT
        ,RESERVATION_ID
        ,RESERVATION_STATUS_CD
        ,RATE_PLAN
        ,WING_CD
        ,ROOM_TYPE
        ,ROOM_NBR
        ,GUEST_UNIQUE_ID
    FROM DAAS_CORE_HOTEL.VIP_AWARD_TIER_TAG
    QUALIFY ROW_NUMBER() OVER (PARTITION BY RESERVATION_ID, PROPERTY_CD ORDER BY UPDATED_DTTM DESC) = 1
) AS VIP_AWARD_TIER_TAG
LEFT JOIN DAAS_CORE_CUSTOMER.GUEST_DIM_VW
    ON
        VIP_AWARD_TIER_TAG.GUEST_UNIQUE_ID = GUEST_DIM_VW.GUEST_UNIQUE_ID AND
        GUEST_DIM_VW.DELETE_IND = 'N'
LEFT JOIN (
    SELECT
        CASE
            WHEN EXPIRE_DT = '1899-12-31 00:00:00.000' THEN '9999-12-31'
            ELSE EXPIRE_DT
        END AS EXPIRE_DT
        ,TIER_ASSIGNMENT_DT
        ,GUEST_UNIQUE_ID
        ,TIER_CD
    FROM DAAS_CORE_CUSTOMER.GUEST_TIER_DIM_VW
    WHERE DELETE_IND = 'N'
) GUEST_TIER_DIM_VW
    ON
        VIP_AWARD_TIER_TAG.GUEST_UNIQUE_ID = GUEST_TIER_DIM_VW.GUEST_UNIQUE_ID AND
        VIP_AWARD_TIER_TAG.ARRIVAL_DT BETWEEN GUEST_TIER_DIM_VW.TIER_ASSIGNMENT_DT AND GUEST_TIER_DIM_VW.EXPIRE_DT
LEFT JOIN DAAS_CORE_CUSTOMER.GUEST_TIERSCORE_DIM_VW
    ON
        VIP_AWARD_TIER_TAG.GUEST_UNIQUE_ID = GUEST_TIERSCORE_DIM_VW.GUEST_UNIQUE_ID AND
        GUEST_TIERSCORE_DIM_VW.ACTIVE_FLG = 'Y' AND
        GUEST_TIERSCORE_DIM_VW.YEAR = YEAR(CURRENT_DATE())
LEFT JOIN DAAS_CORE_HOTEL_VW.HOTEL_GUEST_RESERVATIONS_FACT_VW
    ON
        VIP_AWARD_TIER_TAG.RESERVATION_ID = HOTEL_GUEST_RESERVATIONS_FACT_VW.RESERVATION_ID AND
        VIP_AWARD_TIER_TAG.PROPERTY_CD = HOTEL_GUEST_RESERVATIONS_FACT_VW.PROPERTY_CD AND
        VIP_AWARD_TIER_TAG.ARRIVAL_DT = HOTEL_GUEST_RESERVATIONS_FACT_VW.ARRIVAL_DT AND
        HOTEL_GUEST_RESERVATIONS_FACT_VW.DELETE_IND = 'N'
LEFT JOIN DAAS_CORE_HOTEL_VW.HOTEL_CONFIRMATION_VW
    ON
        VIP_AWARD_TIER_TAG.RESERVATION_ID = HOTEL_CONFIRMATION_VW.RESERVATION_ID AND
        VIP_AWARD_TIER_TAG.PROPERTY_CD = HOTEL_CONFIRMATION_VW.PROPERTY_CODE
LEFT JOIN DAAS_CORE_HOTEL.HOTEL_RESERVATIONS_VW                          -- DAASI-3864
    ON
        VIP_AWARD_TIER_TAG.RESERVATION_ID = HOTEL_RESERVATIONS_VW.RESERVATION_ID AND
        VIP_AWARD_TIER_TAG.PROPERTY_CD = HOTEL_RESERVATIONS_VW.PROPERTY_CD AND
        VIP_AWARD_TIER_TAG.ARRIVAL_DT = HOTEL_RESERVATIONS_VW.ARRIVAL_DT AND
        HOTEL_RESERVATIONS_VW.DELETE_IND = 'N'
WHERE VIP_AWARD_TIER_TAG.ARRIVAL_DT BETWEEN CURRENT_DATE() AND DATEADD(DAY,6,CURRENT_DATE());
